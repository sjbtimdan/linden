#!/usr/bin/env python3
"""Regenerates the bundled CPI snapshot (CpiSeedData.kt) from the IMF CPI.

Data source: DBnomics mirror of the IMF Consumer Price Index (all items,
monthly), series M.<area>.PCPI_IX. Values are index points; the generated
Kotlin stores them scaled by 100 as integers. Re-run this script to refresh
the snapshot, then commit the generated file.

Usage: python3 tools/gen_cpi.py
"""

import json
import sys
import urllib.request
from datetime import date
from pathlib import Path

# Linden currencies -> (IMF REF_AREA, indicator) codes. U2 = euro area
# (changing composition), whose monthly all-items series is only published
# in the harmonized variant; every other area uses the plain all-items index.
CURRENCY_SERIES = {
    "CHF": ("CH", "PCPI_IX"),
    "CNY": ("CN", "PCPI_IX"),
    "EUR": ("U2", "PCPIHA_IX"),
    "GBP": ("GB", "PCPI_IX"),
    "HKD": ("HK", "PCPI_IX"),
    "IDR": ("ID", "PCPI_IX"),
    "INR": ("IN", "PCPI_IX"),
    "JPY": ("JP", "PCPI_IX"),
    "SGD": ("SG", "PCPI_IX"),
    "USD": ("US", "PCPI_IX"),
}

URL = "https://api.db.nomics.world/v22/series/IMF/CPI/M.{area}.{indicator}?observations=1"
OUT = (
    Path(__file__).resolve().parent.parent
    / "shared/src/commonMain/kotlin/org/sjbtimdan/linden/inflation/CpiSeedData.kt"
)
MAX_CHUNK = 100


def fetch(area, indicator):
    url = URL.format(area=area, indicator=indicator)
    request = urllib.request.Request(url, headers={"User-Agent": "linden-cpi-generator"})
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = json.load(response)
    doc = payload["series"]["docs"][0]
    return doc["period"], doc["value"]


def is_valid(value):
    return value is not None and value != "NA"


def clean(months, values):
    """Trim leading/trailing gaps, carry the previous value over interior gaps."""
    pairs = list(zip(months, values))
    start = 0
    while start < len(pairs) and not is_valid(pairs[start][1]):
        start += 1
    end = len(pairs)
    while end > start and not is_valid(pairs[end - 1][1]):
        end -= 1
    pairs = pairs[start:end]

    out_months, out_values, filled, previous = [], [], 0, None
    for month, value in pairs:
        if is_valid(value):
            point = float(value)
        else:
            point = previous
            filled += 1
        previous = point
        out_months.append(month)
        out_values.append(int(point * 100 + 0.5))
    return out_months, out_values, filled


def chunks(values):
    result, current = [], ""
    for value in values:
        piece = f"{value},"
        if current and len(current) + len(piece) > MAX_CHUNK:
            result.append(current)
            current = ""
        current += piece
    if current:
        result.append(current)
    return result


def series_block(code, months, values):
    lines = [
        f'        "{code}" to CpiSeries(',
        f'            "{months[0]}",',
        "            ints(",
    ]
    lines += [f'                "{chunk}",' for chunk in chunks(values)]
    lines += ["            ),", "        ),"]
    return "\n".join(lines)


def main():
    fetched = date.today().isoformat()
    blocks, coverage = [], []
    for code, (area, indicator) in CURRENCY_SERIES.items():
        months, values = None, None
        last_error = None
        for _ in range(3):
            try:
                months, values = fetch(area, indicator)
                break
            except Exception as error:  # noqa: BLE001 - retry network failures
                last_error = error
        if months is None:
            print(f"{code}: fetch failed: {last_error}", file=sys.stderr)
            return 1
        months, values, filled = clean(months, values)
        if not values:
            print(f"{code}: no usable observations", file=sys.stderr)
            return 1
        gap_note = f", {filled} gaps carried" if filled else ""
        coverage.append(f"//   {code} {months[0]}..{months[-1]} ({len(values)} months{gap_note})")
        blocks.append(series_block(code, months, values))
        print(f"{code}: {months[0]}..{months[-1]} ({len(values)} values{gap_note})")

    text = "\n".join(
        [
            "// Generated by tools/gen_cpi.py — do not edit by hand.",
            f"// Source: IMF Consumer Price Index, all items, monthly (via DBnomics). Fetched: {fetched}.",
            "// Monthly index points scaled by 100; the first value belongs to the series' firstMonth.",
            "// Series coverage:",
            *coverage,
            "",
            "package org.sjbtimdan.linden.inflation",
            "",
            "internal object CpiSeedData {",
            f'    const val SOURCE = "IMF Consumer Price Index (via DBnomics)"',
            f'    const val FETCHED = "{fetched}"',
            "",
            "    val series: Map<String, CpiSeries> = mapOf(",
            *blocks,
            "    )",
            "}",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
